import { readFile, writeFile } from 'node:fs/promises';

const sourcePath = new URL('../data/wordfreq-en-25000-log.json', import.meta.url);
const dictionaryPath = new URL('../data/enable1.txt', import.meta.url);
const outputPath = new URL('../src/common-words.js', import.meta.url);

// Vulgar words that appear in the ENABLE dictionary but do not belong in a family puzzle.
const blockedWords = new Set([
  'arse', 'arsehole', 'arses', 'bastard', 'bastards', 'bitch', 'bitches', 'boner', 'boners',
  'boob', 'boobs', 'bugger', 'buggered', 'buggers', 'bullshit', 'clit', 'clits', 'cock',
  'cocks', 'crap', 'crappy', 'craps', 'cunt', 'cunts', 'dick', 'dicks', 'dildo', 'dildos',
  'fuck', 'fucked', 'fucker', 'fuckers', 'fucking', 'fucks', 'jism', 'jizz', 'milf', 'milfs',
  'nigger', 'niggers', 'penis', 'penises', 'pissed', 'pisser', 'pisses', 'porn', 'porno',
  'pube', 'pubes', 'pussies', 'pussy', 'queef', 'rape', 'raped', 'rapes', 'raping', 'rapist',
  'rapists', 'scrotum', 'semen', 'shat', 'shit', 'shits', 'shitty', 'slut', 'sluts', 'smegma',
  'spunk', 'tits', 'titties', 'titty', 'turd', 'turds', 'twat', 'twats', 'vagina', 'vaginas',
  'wank', 'wanker', 'wankers', 'whore', 'whores',
]);

const source = JSON.parse(await readFile(sourcePath, 'utf8'));
const words = source
  .map(([word]) => word.toLowerCase())
  .filter((word) => /^[a-z]+$/.test(word));

const dictionary = new Set(
  (await readFile(dictionaryPath, 'utf8')).split('\n').map((word) => word.trim().toLowerCase()),
);

const uniqueWords = [...new Set(words)];
const excludedWords = uniqueWords.filter((word) => !dictionary.has(word) || blockedWords.has(word));

const moduleSource = `// Generated by scripts/build-word-list.mjs from data/wordfreq-en-25000-log.json.
// Source: aparrish/wordfreq-en-25000, derived from wordfreq data.
// License: Creative Commons Attribution-ShareAlike 4.0.
export const COMMON_WORDS = ${JSON.stringify(uniqueWords, null, 2)};

// Words above that are missing from the ENABLE dictionary (data/enable1.txt, public domain)
// or blocked as unsuitable: proper nouns, tokenizer artifacts, contraction fragments, vulgarities.
export const EXCLUDED_WORDS = ${JSON.stringify(excludedWords, null, 2)};
`;

await writeFile(outputPath, moduleSource);
console.log(`Wrote ${uniqueWords.length} words (${excludedWords.length} excluded from the curated list).`);
